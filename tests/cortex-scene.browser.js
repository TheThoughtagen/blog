async (page) => {
  const checks = [], errors = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto('http://127.0.0.1:4173/work/#plant3d', { waitUntil: 'domcontentloaded' });
  const scene = page.locator('[data-cortex-scene]');
  await scene.waitFor({ state: 'attached', timeout: 30000 });
  await scene.evaluate(element => element.scrollIntoView({ block: 'start', behavior: 'instant' }));
  await page.waitForFunction(() => document.querySelector('[data-cortex-scene]')?.dataset.sceneReady === 'true', null, { timeout: 45000 });
  check(await scene.getAttribute('data-scene-assets') === '15', 'Native Cortex GLB renderer loads all 15 equipment assets');
  check(await page.locator('[data-scene-canvas] canvas').count() === 1, 'Cortex renders the generated model in WebGL');
  check((await scene.textContent()).includes('GENERATED TELEMETRY'), 'Model and readings are clearly identified as demonstration data');
  await scene.screenshot({ path: 'test-results/cortex-plant3d-overview.png' });
  const select = page.locator('[data-scene-equipment]');
  const snapshot = await (await page.request.get('http://127.0.0.1:4173/assets/graph/cortex.json')).json();
  const unit = label => snapshot.nodes.find(node => node.label === label).id;
  await select.selectOption(unit('Unit 01'));
  await page.waitForFunction(() => document.querySelector('[data-scene-name]')?.textContent === 'Unit 01');
  check(await page.locator('[data-scene-reading]').count() === 4, 'Selected equipment exposes four mapped historian channels');
  check((await page.locator('[data-scene-readings]').textContent()).includes('Temperature'), 'Readings include engineering units, signal aliases, and quality');
  check(await page.locator('[data-scene-trend] path').count() >= 3, 'The native Cortex sparkline helper draws 24-hour history and cursor');
  const before = await scene.getAttribute('data-read-at');
  await page.waitForFunction(value => document.querySelector('[data-cortex-scene]')?.dataset.readAt !== value, before, { timeout: 12000 });
  check(true, 'Live demo readings refresh automatically');
  await page.locator('[data-scene-history]').click();
  check(await page.locator('[data-scene-history]').getAttribute('aria-pressed') === 'true', 'Historical mode can be selected');
  const slider = page.locator('[data-scene-scrub]');
  await slider.focus(); await slider.press('Home');
  const oldest = await scene.getAttribute('data-read-at');
  await slider.press('End');
  const newest = await scene.getAttribute('data-read-at');
  check(Date.parse(newest) - Date.parse(oldest) === 86400000, 'The scrubber spans a full 24 hours');
  await slider.press('ArrowLeft');
  const cursor = await scene.getAttribute('data-read-at');
  await scene.screenshot({ path: 'test-results/cortex-plant3d-history.png' });
  check(Date.parse(newest) - Date.parse(cursor) === 60000, 'Keyboard scrubbing advances by one minute');
  const firstSignals = await page.locator('[data-scene-readings] small').allTextContents();
  await select.selectOption(unit('Unit 02'));
  check(await scene.getAttribute('data-read-at') === cursor, 'Changing equipment preserves the historical cursor');
  check(JSON.stringify(await page.locator('[data-scene-readings] small').allTextContents()) !== JSON.stringify(firstSignals), 'Changing equipment loads that unit’s mapped signals');
  await slider.focus(); await slider.press('Home');
  await page.locator('[data-scene-play]').click();
  await page.waitForFunction(() => Number(document.querySelector('[data-scene-scrub]').value) > 0, null, { timeout: 6000 });
  check(await page.locator('[data-scene-play]').getAttribute('aria-pressed') === 'true', 'Historical playback moves through the window');
  await page.locator('[data-scene-play]').click();
  check(await page.locator('[data-scene-play]').getAttribute('aria-pressed') === 'false', 'Historical playback can pause');
  await page.locator('[data-scene-live]').click();
  check(await scene.getAttribute('data-scene-mode') === 'live', 'Returning to live restores current readings');
  await page.locator('[data-scene-fidelity]').check();
  check(await select.inputValue() === unit('Unit 02'), 'Fidelity coloring preserves the equipment selection');
  await scene.screenshot({ path: 'test-results/cortex-plant3d-readings.png' });
  await page.locator('[data-scene-graph]').click();
  await page.waitForFunction(() => document.querySelector('[data-cortex-node-name]')?.textContent === 'Unit 02');
  check((await page.locator('[data-cortex-properties]').textContent()).includes('Design capacity'), '3D selection opens the same equipment and properties in the graph');
  await page.locator('[data-cortex-model]').click();
  check(await select.inputValue() === unit('Unit 02'), 'Graph selection opens the same equipment in 3D');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await scene.evaluate(element => element.scrollIntoView({ block: 'start', behavior: 'instant' }));
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `3D model and telemetry fit ${width}px`);
    const box = await page.locator('[data-scene-canvas]').boundingBox();
    check(box.width > 260 && box.height >= 380, `Interactive 3D canvas remains usable at ${width}px`);
    check(await page.locator('[data-scene-readings]').evaluate(element => element.scrollWidth <= element.clientWidth), `Reading cards fit ${width}px`);
    await select.selectOption(unit('Unit 03'));
    check(await page.locator('[data-scene-name]').textContent() === 'Unit 03', `Equipment selection works at ${width}px`);
    await page.waitForFunction(() => {
      const element = document.querySelector('[data-scene-canvas]');
      const frame = element.getBoundingClientRect();
      const label = element.querySelector('[class*="pointer-events-none"]')?.getBoundingClientRect();
      return label && label.left >= frame.left && label.right <= frame.right && label.top >= frame.top && label.bottom <= frame.bottom;
    }, null, { timeout: 5000 });
    check(true, `Model overlay label stays within the ${width}px canvas`);
    if (width === 320) await scene.screenshot({ path: 'test-results/cortex-plant3d-mobile.png' });
  }
  check(errors.length === 0, `Model, telemetry, graph links and viewport changes have no page errors: ${errors.join('; ')}`);
  return { passed: checks.length, checks };
}
